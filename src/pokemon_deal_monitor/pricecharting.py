"""PriceCharting API client for ungraded and graded card prices."""

import json
import logging
import re
import time
import urllib.parse
import urllib.request
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path

from .catalog import DATA_DIR
from .ebay import Transport, urllib_transport
from .games.pokemon.catalog import GAME, PokemonCard, Variant
from .matcher import card_number_key, normalize


API_URL = "https://www.pricecharting.com/api"

# PriceCharting allows at most one API call per second.
MIN_SECONDS_BETWEEN_CALLS = 1.0

# Cloudflare in front of PriceCharting answers sustained bursts with HTTP
# 429 even within the documented limit, or sometimes by dropping the
# connection. Back off and retry either: 30s, 60s, ...
RATE_LIMIT_RETRIES = 4
RATE_LIMIT_BACKOFF_SECONDS = 30.0

logger = logging.getLogger(__name__)

# Maps catalog card identifiers to PriceCharting product IDs. Generated by
# scripts/map_pricecharting.py and reviewed by hand.
PRODUCT_IDS_PATH = DATA_DIR / GAME / "pricecharting_ids.json"


# Bracketed product-name tags that mark a different printing of a card.
EXCLUDED_TAGS = re.compile(
    r"error|misprint|staff|prerelease|stamp|jumbo|gold|winner|sample|"
    r"no symbol|test|japanese|non holo"
)
# PriceCharting files non-English printings under their own consoles, such as
# "Pokemon Japanese Neo Genesis" or "Pokemon Korean Base Set".
NON_ENGLISH_CONSOLES = re.compile(
    r"\b(japanese|korean|chinese|french|german|italian|spanish|portuguese|dutch)\b"
)
# Sets with one English printing per card, so PriceCharting names the
# product without a [Reverse Holo] tag even when the card is a reverse holo.
SINGLE_PRINTING_SETS = {"Southern Islands", "Wizards Black Star Promos"}
# PriceCharting consoles for sets it doesn't name after the set. Its plain
# promos are untagged, e.g. "Mewtwo #3", or tagged [WOTC] where a modern
# promo shares the number; every other tag is a variant.
CONSOLE_NAMES = {"Wizards Black Star Promos": "pokemon promo"}
SEARCH_SET_NAMES = {"Wizards Black Star Promos": "Promo"}
PRODUCT_NUMBER_PATTERN = re.compile(r"#\s*(h?)0*(\d+)")


class PriceChartingError(Exception):

    def __init__(self, status: int, message: str):
        super().__init__(f"PriceCharting returned HTTP {status}: {message}")
        self.status = status


@dataclass(frozen=True)
class PriceChartingPrice:
    product_id: str
    product_name: str
    # Prices in cents; None when PriceCharting has no value for that grade.
    ungraded_cents: int | None
    grade_5_cents: int | None
    grade_7_cents: int | None
    # Units sold over the last year, across all grades.
    sales_volume: int | None


def optional_int(value) -> int | None:
    if value in (None, ""):
        return None
    return int(value)


def parse_product(product: dict) -> PriceChartingPrice:
    # PriceCharting reuses video game field names for card grades:
    # "loose" is ungraded and "cib" is grade 7.
    return PriceChartingPrice(
        product_id=str(product["id"]),
        product_name=product.get("product-name", ""),
        ungraded_cents=optional_int(product.get("loose-price")),
        grade_5_cents=optional_int(product.get("condition-15-price")),
        grade_7_cents=optional_int(product.get("cib-price")),
        sales_volume=optional_int(product.get("sales-volume")),
    )


def search_query(card: PokemonCard) -> str:
    _, numerator = card_number_key(card.number)
    set_name = SEARCH_SET_NAMES.get(card.set_name, card.set_name)
    return f"{card.name} {set_name} #{numerator.upper()}"


def product_matches(card: PokemonCard, product: dict) -> bool:
    """Return whether a PriceCharting product is this exact catalog card."""
    console = normalize(product.get("console-name", ""))
    if card.set_name in CONSOLE_NAMES:
        if console != CONSOLE_NAMES[card.set_name]:
            return False
    elif normalize(card.set_name) not in console or NON_ENGLISH_CONSOLES.search(console):
        return False
    if card.set_name == "Base Set" and "base set 2" in console:
        return False

    name = product.get("product-name", "")
    number = PRODUCT_NUMBER_PATTERN.search(name.lower())
    _, numerator = card_number_key(card.number)
    if number is None or f"{number[1]}{number[2]}" != numerator:
        return False
    if not re.search(rf"\b{re.escape(normalize(card.name))}\b", normalize(name)):
        return False

    tags = " ".join(normalize(tag) for tag in re.findall(r"\[([^\]]+)\]", name))
    if EXCLUDED_TAGS.search(tags):
        return False
    if ("1st edition" in tags) != card.first_edition_required:
        return False
    if card.set_name in CONSOLE_NAMES:
        return tags in ("", "wotc")
    if card.set_name in SINGLE_PRINTING_SETS:
        return "reverse" in tags or not tags
    if ("reverse" in tags) != (card.variant == Variant.REVERSE_HOLO):
        return False

    return True


def select_products(
    card: PokemonCard,
    products: list[dict],
    tcg_product_id: int | None = None,
) -> list[dict]:
    """Return the search results that are this card.

    When several remain, the TCGplayer product ID breaks the tie.
    """
    matches = [p for p in products if product_matches(card, p)]
    if len(matches) > 1 and tcg_product_id is not None:
        same_tcg = [
            p for p in matches if str(p.get("tcg-id")) == str(tcg_product_id)
        ]
        if same_tcg:
            matches = same_tcg
    return matches


def load_product_ids(path: Path = PRODUCT_IDS_PATH) -> dict[str, str]:
    if not path.exists():
        return {}
    entries = json.loads(path.read_text(encoding="utf-8"))
    return {
        identifier: entry["product_id"]
        for identifier, entry in entries.items()
        if entry.get("product_id")
    }


class PriceChartingClient:

    def __init__(
        self,
        token: str,
        transport: Transport = urllib_transport,
        clock: Callable[[], float] = time.monotonic,
        sleep: Callable[[float], None] = time.sleep,
        min_seconds_between_calls: float = MIN_SECONDS_BETWEEN_CALLS,
    ):
        self.token = token
        self.transport = transport
        self.clock = clock
        self.sleep = sleep
        self.min_seconds_between_calls = min_seconds_between_calls
        self._last_call_at: float | None = None

    def product(self, product_id: str) -> PriceChartingPrice:
        return parse_product(self._get("product", id=product_id))

    def search(self, query: str) -> list[dict]:
        """Return up to 20 raw product records matching a search."""
        return self._get("products", q=query).get("products", [])

    def _get(self, endpoint: str, **params) -> dict:
        query = urllib.parse.urlencode({"t": self.token, **params})
        url = f"{API_URL}/{endpoint}?{query}"

        for attempt in range(RATE_LIMIT_RETRIES + 1):
            last_attempt = attempt == RATE_LIMIT_RETRIES
            try:
                status, body = self._send(url)
            except OSError:
                if last_attempt:
                    raise
            else:
                if status != 429 or last_attempt:
                    break
            wait = RATE_LIMIT_BACKOFF_SECONDS * 2 ** attempt
            logger.info("PriceCharting is throttling requests; retrying in %.0fs",
                        wait)
            self.sleep(wait)

        try:
            payload = json.loads(body)
        except ValueError:
            payload = None
        if not isinstance(payload, dict):
            payload = {}

        if status != 200 or payload.get("status") != "success":
            message = payload.get("error-message")
            if message is None:
                # Cloudflare returns HTML pages rather than JSON errors.
                message = (
                    "rate limited" if status == 429
                    else body[:200].decode(errors="replace")
                )
            raise PriceChartingError(status, message)
        return payload

    def _send(self, url: str) -> tuple[int, bytes]:
        if self._last_call_at is not None:
            elapsed = self.clock() - self._last_call_at
            wait = self.min_seconds_between_calls - elapsed
            if wait > 0:
                self.sleep(wait)
        self._last_call_at = self.clock()
        return self.transport(urllib.request.Request(url))
